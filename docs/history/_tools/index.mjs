#!/usr/bin/env node
// Prints the two indexes over `docs/history/`, from the entries' own front
// matter. Nothing it prints is committed: a committed index is a single line
// every session edits, which is the write point the split removed. Regenerate
// it whenever you want one; `grep -r` over the directory is the primary way to
// find an entry, and the front matter carries everything these indexes key on.
//
//   npm run history:index                 -- print to stdout
//   npm run history:index -- --out <path> -- write a file (keep it out of git)
//
// The migration index is INVERTED from each entry's `migrations:` list. There
// is no migration -> entry table to maintain, and there must not be: it is a
// many-to-many mapping and a second copy of it is the copy that goes stale.
// (The pre-split `docs/HISTORY.md` carried exactly such a table, and it had
// stopped at 0016 while the chain stood at 0025.)
//
// Ported from idea-app's `docs/history/_tools/index.mjs`; the GREENLINE index
// there is specific to that repo and is not carried over.

import { readdirSync, writeFileSync } from 'node:fs';
import { readEntries } from './front-matter.mjs';

const MIGRATIONS_DIR = new URL('../../../supabase/migrations/', import.meta.url).pathname;

// The order groups are printed in. A subsystem an entry names that is not
// listed here still prints, at the end, so a new subsystem is never silently
// dropped -- it is simply unsorted until someone adds it.
const GROUP_ORDER = [
	'Foundation, auth, schema',
	'Mentor console',
	'Student runtime',
	'Roster, parents, match runs',
	'Skill Hub, notebook',
	'Route planner, field picture',
	'Code generator',
	'Visual theme, brand',
	'Build, tests, conventions'
];

const entries = readEntries();

// Record order for the pre-split archive; date then filename for everything
// after it, which is where every new entry lands.
const position = (e) => (Number.isInteger(e.record_order) ? [0, e.record_order, ''] : [1, 0, `${e.date} ${e.file}`]);
const byPosition = (a, b) => {
	const [ak, an, as] = position(a);
	const [bk, bn, bs] = position(b);
	return ak - bk || an - bn || as.localeCompare(bs);
};
entries.sort(byPosition);

const link = (e) => `[${e.title}](${e.file})`;
const out = [];
const w = (s = '') => out.push(s);

w('# Index of `docs/history/`');
w();
w('GENERATED by `npm run history:index` from the front matter of every file in');
w('this directory. Do not commit it and do not edit it: it is rebuilt from the');
w('entries, and the entries are the record.');
w();
w(`${entries.length} entries. Generated ${new Date().toISOString().slice(0, 10)}.`);
w();
w('---');
w();

// --- 1. by subsystem --------------------------------------------------------
w('## Index by subsystem');
w();
const groups = new Map();
for (const e of entries) {
	for (const g of e.subsystems.length ? e.subsystems : ['(no subsystem)']) {
		if (!groups.has(g)) groups.set(g, []);
		groups.get(g).push(e);
	}
}
const known = GROUP_ORDER.filter((g) => groups.has(g));
const rest = [...groups.keys()].filter((g) => !GROUP_ORDER.includes(g)).sort();
for (const g of [...known, ...rest]) {
	w(`### ${g}`);
	w();
	for (const e of groups.get(g)) w(`- ${link(e)}`);
	w();
}

// --- 2. by migration --------------------------------------------------------
w('---');
w();
w('## Index by migration');
w();
w("Inverted from each entry's `migrations:` list. A migration with no entry of its");
w('own is documented inside the one listed.');
w();
w('| # | File | Documented in |');
w('|---|---|---|');
const byMigration = new Map();
for (const e of entries) {
	for (const m of e.migrations) {
		if (!byMigration.has(m)) byMigration.set(m, []);
		byMigration.get(m).push(e);
	}
}
// Every row comes from `supabase/migrations/` on disk, not from what the
// entries happen to claim, so a migration nobody documented still gets a row
// and says so. A number an entry claims that has no file gets a row too.
const files = new Map();
try {
	for (const f of readdirSync(MIGRATIONS_DIR).sort()) {
		const m = /^(\d{4})_.*\.sql$/.exec(f);
		if (m) files.set(m[1], f);
	}
} catch {
	console.error(`note: ${MIGRATIONS_DIR} is unreadable; listing only the migrations the entries claim`);
}
const numbers = [...new Set([...files.keys(), ...byMigration.keys()])].sort();
let undocumented = 0;
for (const m of numbers) {
	const docs = byMigration.get(m);
	if (!docs) undocumented += 1;
	const where = docs ? docs.sort(byPosition).map(link).join('; ') : '_(not documented in the record -- read the SQL)_';
	w(`| ${m} | ${files.has(m) ? `\`${files.get(m)}\`` : '_(no file on disk)_'} | ${where} |`);
}
w();
w(`${numbers.length} migrations, ${undocumented} of them documented by no entry.`);
w();

const text = out.join('\n');
const flag = process.argv.indexOf('--out');
if (flag >= 0) {
	const path = process.argv[flag + 1];
	if (!path) throw new Error('--out needs a path (write it somewhere outside the repo, or delete it before committing)');
	writeFileSync(path, text);
	console.error(`wrote ${path} (${entries.length} entries, ${numbers.length} migrations)`);
} else {
	process.stdout.write(text);
}
