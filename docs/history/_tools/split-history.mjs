#!/usr/bin/env node
// ONE-SHOT: the 2026-09-02 split of `docs/HISTORY.md` into `docs/history/`,
// one file per entry. Kept as the record of how the split was done and that
// it was mechanical rather than retyped, the way idea-app keeps its own
// `_tools/split-*` scripts. It refuses to overwrite a file that already
// exists, so running it a second time is an error rather than a rewrite.
//
// What it does, exactly:
//   * takes the record body: every byte from the FIRST entry heading
//     (`## YYYY-MM-DD -- ...`) to the end of the file. The preamble above it
//     (when to read, how to append, the migration index) is dropped: the
//     "how to append" is replaced by CLAUDE.md's History section and the
//     migration index is regenerated by `index.mjs` from front matter;
//   * cuts that body at every `## ` heading (every one of them is an entry
//     heading; the file was checked for a `## ` inside an entry first);
//   * writes each entry as `record-<slug>.md`: a front-matter block, ONE blank
//     line, then the entry body byte for byte, WITHOUT its `## ` heading. The
//     heading is derived from `title` at read time (see verify-split.mjs),
//     which is idea-app's shape after `derive-headings.mjs` and the reason
//     that one-shot is not ported: this split never wrote the second copy.
//
// Front matter per entry: `title` (the heading text verbatim, date prefix
// included, so reassembly is byte-exact), `date`, `branches` (empty: every
// pre-split bundle was committed straight to main under the old "do not
// create branches" rule), `migrations` (from the table below, checked by
// hand against each entry's own `NNNN_` mentions), `subsystems`, and
// `record_order`, the entry's 1-based position in the pre-split file.
//
// Run: node docs/history/_tools/split-history.mjs   (once, ever)

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { HISTORY_DIR } from './front-matter.mjs';

const SOURCE = new URL('../../HISTORY.md', import.meta.url).pathname;
const HEADING = /^## (\d{4}-\d{2}-\d{2}) -- (.+)$/;

// record_order -> migrations. Rows 1-8 come from the pre-split file's own
// migration index table; 9 onward from each entry's `NNNN_<name>.sql`
// mentions, read entry by entry (0018 is named at line 1696 of the pre-split
// file, inside entry 10; 0025 at line 4599, inside entry 27). An entry that
// repaired the ledger or mentioned an earlier file in passing lists nothing.
const MIGRATIONS = {
	1: ['0001', '0002', '0003', '0004', '0005', '0006', '0007', '0008'],
	3: ['0009'],
	4: ['0010'],
	5: ['0011'],
	6: ['0012'],
	7: ['0013', '0014', '0015'],
	8: ['0016'],
	9: ['0017'],
	10: ['0018'],
	11: ['0019', '0020'],
	16: ['0021', '0022'],
	17: ['0023'],
	19: ['0024'],
	27: ['0025']
};

// record_order -> subsystems (the groups index.mjs prints, in its order).
const SUBSYSTEMS = {
	1: ['Foundation, auth, schema'],
	2: ['Foundation, auth, schema', 'Build, tests, conventions'],
	3: ['Mentor console'],
	4: ['Student runtime'],
	5: ['Skill Hub, notebook'],
	6: ['Route planner, field picture'],
	7: ['Roster, parents, match runs'],
	8: ['Skill Hub, notebook'],
	9: ['Route planner, field picture'],
	10: ['Visual theme, brand'],
	11: ['Roster, parents, match runs'],
	12: ['Visual theme, brand'],
	13: ['Route planner, field picture'],
	14: ['Route planner, field picture'],
	15: ['Foundation, auth, schema'],
	16: ['Foundation, auth, schema', 'Build, tests, conventions'],
	17: ['Foundation, auth, schema'],
	18: ['Route planner, field picture'],
	19: ['Code generator'],
	20: ['Code generator'],
	21: ['Code generator'],
	22: ['Code generator'],
	23: ['Student runtime'],
	24: ['Visual theme, brand'],
	25: ['Code generator'],
	26: ['Visual theme, brand'],
	27: ['Visual theme, brand']
};

const quote = (s) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const list = (xs) => `[${xs.map(quote).join(', ')}]`;
const slugify = (s) =>
	s
		.toLowerCase()
		.replace(/`/g, '')
		.replace(/[^a-z0-9]+/g, '-')
		.replace(/^-+|-+$/g, '')
		.slice(0, 80)
		.replace(/-+$/, '');

const text = readFileSync(SOURCE, 'utf8');
const lines = text.split('\n');
const first = lines.findIndex((l) => HEADING.test(l));
if (first < 0) throw new Error('no entry heading found');
const body = lines.slice(first).join('\n');

// Cut at every "## " line. Each chunk is "## <title>\n\n<rest>".
const chunks = [];
let cur = null;
for (const line of body.split('\n')) {
	if (/^## /.test(line)) {
		if (cur) chunks.push(cur);
		cur = [line];
	} else {
		cur.push(line);
	}
}
chunks.push(cur);

let reassembled = '';
const seen = new Set();
chunks.forEach((chunk, i) => {
	const order = i + 1;
	const m = HEADING.exec(chunk[0]);
	if (!m) throw new Error(`entry ${order}: heading is not dated: ${chunk[0]}`);
	if (chunk[1] !== '') throw new Error(`entry ${order}: no blank line after the heading`);
	const [, date, rest] = m;
	const title = chunk[0].slice(3);
	// The body is everything after the heading and its blank line, verbatim.
	// split() removed the newline between this chunk's last line and the next
	// heading, so every chunk but the last gets it back; the last chunk keeps
	// the file's own trailing newline (split leaves a final '').
	const entryBody = chunk.slice(2).join('\n') + (i === chunks.length - 1 ? '' : '\n');
	const file = `record-${slugify(rest)}.md`;
	if (seen.has(file)) throw new Error(`slug collision: ${file}`);
	seen.add(file);
	const path = join(HISTORY_DIR, file);
	if (existsSync(path)) throw new Error(`${file} already exists; this script runs once`);
	const fm = [
		'---',
		`title: ${quote(title)}`,
		`date: ${date}`,
		'branches: []',
		`migrations: ${list(MIGRATIONS[order] ?? [])}`,
		`subsystems: ${list(SUBSYSTEMS[order] ?? [])}`,
		`record_order: ${order}`,
		'---',
		''
	].join('\n');
	writeFileSync(path, `${fm}\n${entryBody}`);
	reassembled += `## ${title}\n\n${entryBody}`;
	console.log(`${String(order).padStart(2)}  ${date}  ${file}`);
});

if (reassembled !== body) throw new Error('reassembly of the chunks does not equal the source body');
console.log(`\n${chunks.length} entries written; reassembly is byte-identical to the source body (${Buffer.byteLength(body, 'utf8')} bytes).`);
